def solution(numbers):
    """
    > 풀이전략:
      높은자리수부터 우선순위 오름차순 정렬
      단순 수 비교는 안된다.
      30과 3비교 -> 3이 더 우선순위높음
      78와 7비교 -> 78가 더 우선순위높음
      30과 3비교 -> 3이 더 우선순위높음
      
      그냥오름차순: 3, 5, 9, 30, 34
      높은자리수 기준: 3, 30, 34, 5, 9
      같을때는 둘째자리수 기준: 30 34 3 5 9
      
      같을 때 기준은 단순 둘째자리수가 아님
      만약 한자리수라면 해당 수랑 다시 비교하는거임
      
      즉 
      789 -> (7,8, 9, 9)
      78 => (7, 8, 8, 8)
      7 -> (7, 7, 7, 7)
      
      789 > 78 > 7이 된다.
      
      
      문제발생함.
      13 = > (1,3,3,3)
      132 -> (1,3,2,2)
      이때는 13> 132여야하는데 132>13이 됨
      
      13 -> (1,3,1,3)
      132 -> (1,3,2,1)
      
      즉 그냥 마지막수 연장이 아니라 처음부터 반복해 다시 반복
      1,2,3,4자리수 모두 12자로 하면 끊기지 않음
    
    """
 
    def make_key(s): #num=789
        return s* (12//len(s))
    
    rank = sorted(map(str, numbers), key = make_key, reverse=True)
    
    # 0으로 시작하는거 제거, 빈문자열 되면 "0"반환            
    return "".join(map(str,rank)).lstrip("0") or "0"